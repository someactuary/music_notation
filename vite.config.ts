import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { createOmrService } from "./server/omr-service";

/**
 * Mounts the local OMR service (server/omr-service.ts) at /api/omr, localhost only
 * (the Vite dev server already binds to localhost by default). See
 * docs/ARCHITECTURE.md "M4 contracts: PDF import (OMR)".
 */
function omrPlugin(): Plugin {
  return {
    name: "pmn-omr-service",
    configureServer(server) {
      const service = createOmrService({
        jobsDir: path.resolve(__dirname, ".omr-jobs"),
        pdfToPngCommand: ["/usr/bin/swift", path.resolve(__dirname, "scripts", "pdf-to-png.swift")],
      });
      // connect strips the "/api/omr" mount prefix before calling `handle`, so the
      // handler itself only ever sees paths like "/status" or "/jobs/:id".
      server.middlewares.use("/api/omr", service.handle);
      server.httpServer?.once("close", () => {
        void service.shutdown();
      });
    },
  };
}

/** Every file under `dir`, as paths relative to it with forward slashes. */
function listFiles(dir: string, prefix = ""): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    const rel = prefix + name;
    return statSync(full).isDirectory() ? listFiles(full, `${rel}/`) : [rel];
  });
}

/**
 * The website build only (`npm run build:web`, mode "web"): writes `sw.js`, a service
 * worker that saves every file of the app (the bundle and public/: fonts, piano samples,
 * icons) so the site works offline and can be installed. Its cache name is a hash of the
 * file list and the public files' contents, so each publish replaces the old cache.
 * Page loads go to the network first (a new publish shows up right away) and fall back to
 * the saved copy offline; everything else is served from the saved copy.
 */
function offlinePlugin(): Plugin {
  let base = "/";
  let publicDir = "";
  return {
    name: "pmn-offline",
    apply: (_config, env) => env.command === "build" && env.mode === "web",
    configResolved(config) {
      base = config.base;
      publicDir = config.publicDir;
    },
    generateBundle(_options, bundle) {
      const publicFiles = listFiles(publicDir).filter((f) => !f.startsWith(".") && !f.endsWith(".DS_Store"));
      const files = [...Object.keys(bundle), ...publicFiles].filter((f) => !f.endsWith(".map")).sort();
      const hash = createHash("sha256").update(files.join("\n"));
      for (const f of publicFiles) hash.update(readFileSync(path.join(publicDir, f)));
      const version = hash.digest("hex").slice(0, 12);
      const source = `// Generated by vite.config.ts (offlinePlugin) for the website build.
const CACHE = "pmn-${version}";
const BASE = ${JSON.stringify(base)};
const FILES = ${JSON.stringify(files)}.map((f) => BASE + f);

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll([BASE, ...FILES])));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("pmn-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    event.respondWith(fetch(request).catch(() => caches.match(BASE, { ignoreVary: true })));
    return;
  }
  // ignoreVary: servers (GitHub Pages included) send Vary headers, and the page's module
  // script requests carry headers the install-time downloads didn't, so a plain match misses.
  event.respondWith(caches.match(request, { ignoreVary: true }).then((hit) => hit || fetch(request)));
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

export default defineConfig({
  plugins: [react(), omrPlugin(), offlinePlugin()],
  resolve: { alias: { "@": path.resolve(__dirname, "src") } },
  publicDir: "public",
});
